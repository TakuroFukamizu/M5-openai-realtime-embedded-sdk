void pi4ioe_init() {
  // Read CTRL register to get the current state
  // pi4ioe_read_reg(PI4IOE_REG_CTRL);

  // Set outputs to high-impedance
  pi4ioe_write_reg(PI4IOE_REG_IO_PP, 0x00);  // Set to high-impedance
  // pi4ioe_read_reg(PI4IOE_REG_IO_PP);

  // Enable pull-up resistors
  pi4ioe_write_reg(PI4IOE_REG_IO_PULLUP, 0xFF);  // Enable pull-up
  pi4ioe_write_reg(PI4IOE_REG_IO_DIR, 0x6E);     // Set input=0, output=1
  // pi4ioe_read_reg(PI4IOE_REG_IO_DIR);

  // Set outputs to 1
  pi4ioe_write_reg(PI4IOE_REG_IO_OUT, 0xFF);
  // pi4ioe_read_reg(PI4IOE_REG_IO_OUT);
}

void pi4ioe_setMute(bool mute) {
  // PI4IOE register definitions
  pi4ioe_write_reg(PI4IOE_REG_IO_OUT, mute ? 0x00 : 0xFF);
}
